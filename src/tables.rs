//! Baked reflectance tables for the BSDF.
//!
//! Two fits live here, both 32x32 and both indexed the same way: the row is
//! the roughness-like axis, the column is `cos(theta)` of the outgoing
//! direction, and both axes run linearly over `[0, 1]` with the endpoints on
//! the grid. Lookups are bilinear, and `gpu/shaders/tables.wgsl` carries
//! byte-identical numbers so the two renderers agree.
//!
//! Both tables are measured data. Clippy's `approx_constant` fires on a couple
//! of the entries because a reflectance that happens to be 0.52359 is not
//! `PI/6` in disguise, and a sheen coefficient that happens to be 0.30103 is
//! not `log10(2)`.
