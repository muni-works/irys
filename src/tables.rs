/// Bilinear lookup into a `RES x RES` scalar table. Both coordinates are in
/// `[0, 1]`.
#[inline]
pub(crate) fn bilinear(table: &[f32], row: f32, col: f32) -> f32 {
    let (r, rf, c, cf) = index(row, col);
    let t = |i: usize, j: usize| table[i * RES + j];
    (t(r, c) * (1.0 - cf) + t(r, c + 1) * cf) * (1.0 - rf)
        + (t(r + 1, c) * (1.0 - cf) + t(r + 1, c + 1) * cf) * rf
}

/// Bilinear lookup into the three-channel sheen table.
#[inline]
pub(crate) fn bilinear3(table: &[[f32; 3]], row: f32, col: f32) -> [f32; 3] {
    let (r, rf, c, cf) = index(row, col);
    let t = |i: usize, j: usize| table[i * RES + j];
    let mut out = [0.0f32; 3];
    for (k, o) in out.iter_mut().enumerate() {
        *o = (t(r, c)[k] * (1.0 - cf) + t(r, c + 1)[k] * cf) * (1.0 - rf)
            + (t(r + 1, c)[k] * (1.0 - cf) + t(r + 1, c + 1)[k] * cf) * rf;
    }
    out
}

/// Cell indices and interpolation fractions for a `[0, 1]^2` coordinate.
///
/// Clamped just short of 1 so `r + 1` and `c + 1` are always in range.
#[inline]
fn index(row: f32, col: f32) -> (usize, f32, usize, f32) {
    const LAST: f32 = 1.0 - 1e-6;
    let row = row.clamp(0.0, LAST) * (RES - 1) as f32;
    let col = col.clamp(0.0, LAST) * (RES - 1) as f32;
    let r = row.floor();
    let c = col.floor();
    (r as usize, row - r, c as usize, col - c)
}

// ─── the specular lobe's directional albedo ───────────────────────────────
//
// What the specular half of the split denoiser demodulates by. Karis's split
// sum: the single-scattering GGX lobe's directional albedo is
// `F0 · A(r, mu) + B(r, mu)` with `A` the Schlick-weighted part and `B` the
// grazing part, and the two are functions of *perceptual roughness* and the
// view cosine alone. Row `i` is `roughness = i / 31` (alpha is its square,
// floored at 1e-4 exactly as `mat_alpha` floors it), column `j` is
// `mu = j / 31` with the `mu = 0` column at `1e-3`. Each entry is a 64x64
// stratified VNDF estimate over this renderer's own height-correlated Smith
// lobe, so `A + B` is `GGX_E` re-indexed by roughness rather than alpha —
// `tests/spec_albedo.rs` pins that.
//
// Generated by [`split_sum_cell`]; `split_sum_matches_its_generator` in
// this module keeps the baked numbers honest.

/// Samples per axis of the stratified estimate behind each table cell.
#[cfg(test)]
const SPLIT_SUM_STRATA: usize = 64;

/// Smith Λ for isotropic GGX at `alpha`, for a direction with cosine `mu`.
#[cfg(test)]
fn smith_lambda(alpha: f64, mu: f64) -> f64 {
    let mu = mu.max(1e-6);
    let tan2 = (1.0 - mu * mu).max(0.0) / (mu * mu);
    (-1.0 + (1.0 + alpha * alpha * tan2).sqrt()) * 0.5
}

/// One cell of the split-sum tables: `(A, B)` at perceptual `roughness` and
/// view cosine `mu`, by stratified VNDF sampling of the single-scattering
/// lobe. `A` weights `1 - (1 - v·h)^5`, `B` weights `(1 - v·h)^5`, so that
/// `F0 · A + B` is the lobe's directional albedo under Schlick's Fresnel.
#[cfg(test)]
fn split_sum_cell(roughness: f32, mu: f32) -> (f32, f32) {
    let alpha = ((roughness as f64) * (roughness as f64)).max(1e-4);
    let mu = (mu as f64).max(1e-3);
    let wo = [(1.0 - mu * mu).max(0.0).sqrt(), 0.0, mu];
    // Stretch the view into the hemisphere configuration once.
    let vh = {
        let v = [alpha * wo[0], alpha * wo[1], wo[2]];
        let l = (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt();
        [v[0] / l, v[1] / l, v[2] / l]
    };
    let lensq = vh[0] * vh[0] + vh[1] * vh[1];
    let t1 = if lensq > 0.0 {
        let s = lensq.sqrt();
        [-vh[1] / s, vh[0] / s, 0.0]
    } else {
        [1.0, 0.0, 0.0]
    };
    let t2 = [
        vh[1] * t1[2] - vh[2] * t1[1],
        vh[2] * t1[0] - vh[0] * t1[2],
        vh[0] * t1[1] - vh[1] * t1[0],
    ];
    let lambda_o = smith_lambda(alpha, mu);
    let g1_o = 1.0 / (1.0 + lambda_o);

    let n = SPLIT_SUM_STRATA;
    let (mut a, mut b) = (0.0f64, 0.0f64);
    for i in 0..n {
        for j in 0..n {
            let r1 = (i as f64 + 0.5) / n as f64;
            let r2 = (j as f64 + 0.5) / n as f64;
            let r = r1.sqrt();
            let phi = 2.0 * std::f64::consts::PI * r2;
            let p1 = r * phi.cos();
            let p2r = r * phi.sin();
            let s = 0.5 * (1.0 + vh[2]);
            let p2 = (1.0 - s) * (1.0 - p1 * p1).max(0.0).sqrt() + s * p2r;
            let pz = (1.0 - p1 * p1 - p2 * p2).max(0.0).sqrt();
            let nh = [
                t1[0] * p1 + t2[0] * p2 + vh[0] * pz,
                t1[1] * p1 + t2[1] * p2 + vh[1] * pz,
                t1[2] * p1 + t2[2] * p2 + vh[2] * pz,
            ];
            let wh = {
                let v = [alpha * nh[0], alpha * nh[1], nh[2].max(1e-9)];
                let l = (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt();
                [v[0] / l, v[1] / l, v[2] / l]
            };
            let o_dot_h = wo[0] * wh[0] + wo[1] * wh[1] + wo[2] * wh[2];
            if o_dot_h <= 0.0 {
                continue;
            }
            // wi = reflect(-wo, wh)
            let wi = [
                2.0 * o_dot_h * wh[0] - wo[0],
                2.0 * o_dot_h * wh[1] - wo[1],
                2.0 * o_dot_h * wh[2] - wo[2],
            ];
            if wi[2] <= 0.0 {
                continue;
            }
            // f·cos/pdf under VNDF sampling is G2 / G1(wo).
            let g2 = 1.0 / (1.0 + lambda_o + smith_lambda(alpha, wi[2]));
            let w = g2 / g1_o;
            let fc = (1.0 - o_dot_h).powi(5);
            a += (1.0 - fc) * w;
            b += fc * w;
        }
    }
    let k = (n * n) as f64;
    ((a / k) as f32, (b / k) as f32)
}

/// Directional albedo of the specular lobe at `f0`, perceptual `roughness`
/// and view cosine `mu`, per channel: the split sum with Turquin's
/// multiple-scattering compensation folded in, so it is the albedo of the
/// lobe `pathtrace` actually shades with. Mirrored bit-for-bit (in f32) by
/// `spec_albedo_lookup` in `bsdf.wgsl`; the GPU parity test pins the two.
pub fn spec_albedo(f0: [f32; 3], roughness: f32, mu: f32) -> [f32; 3] {
    let r = roughness.clamp(0.0, 1.0);
    let a = bilinear(&SPLIT_SUM_A, r, mu);
    let b = bilinear(&SPLIT_SUM_B, r, mu);
    let alpha = (r * r).max(1e-4);
    let e = bilinear(&GGX_E, alpha, mu).clamp(1e-3, 1.0);
    let mut out = [0.0f32; 3];
    for k in 0..3 {
        let ss = f0[k] * a + b;
        out[k] = ss * (1.0 + f0[k] * ((1.0 - e) / e));
    }
    out
}

