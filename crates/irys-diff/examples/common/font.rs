//! A 5 × 7 bitmap font for the skin examples' labels.

/// Uppercase, digits and a little punctuation in a 5 × 7 bitmap, drawn
/// white on a darkened box at `(x, y)`, each font pixel `scale` image pixels.
pub fn text(px: &mut [u8], w: usize, x: usize, y: usize, s: &str, scale: usize) {
    let glyphs: Vec<[u8; 7]> = s.chars().map(glyph).collect();
    let (gw, gh) = (6 * scale, 7 * scale);
    let (bw, bh) = (glyphs.len() * gw + 2 * scale, gh + 4 * scale);
    let h = px.len() / 3 / w;
    for yy in y..(y + bh).min(h) {
        for xx in x..(x + bw).min(w) {
            for c in 0..3 {
                let p = &mut px[(yy * w + xx) * 3 + c];
                *p = (*p as u32 * 2 / 5) as u8;
            }
        }
    }
    for (k, g) in glyphs.iter().enumerate() {
        for (row, bits) in g.iter().enumerate() {
            for col in 0..5 {
                if bits >> (4 - col) & 1 == 0 {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        let xx = x + scale + k * gw + col * scale + dx;
                        let yy = y + 2 * scale + row * scale + dy;
                        if xx < w && yy < h {
                            px[(yy * w + xx) * 3..(yy * w + xx) * 3 + 3]
                                .copy_from_slice(&[240, 240, 240]);
                        }
                    }
                }
            }
        }
    }
}

