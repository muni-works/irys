//! A 5 × 7 bitmap font (irys-diff's, with the letters and signs a report
//! needs), drawn in a colour onto RGB8.

/// Draw `s` at `(x, y)` in `rgb`, each font pixel `scale` image pixels.
pub fn text(px: &mut [u8], w: usize, x: usize, y: usize, s: &str, scale: usize, rgb: [u8; 3]) {
    let h = px.len() / 3 / w;
    for (k, ch) in s.chars().enumerate() {
        let g = glyph(ch);
        for (row, bits) in g.iter().enumerate() {
            for col in 0..5 {
                if bits >> (4 - col) & 1 == 0 {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        let xx = x + k * 6 * scale + col * scale + dx;
                        let yy = y + row * scale + dy;
                        if xx < w && yy < h {
                            px[(yy * w + xx) * 3..(yy * w + xx) * 3 + 3].copy_from_slice(&rgb);
                        }
                    }
                }
            }
        }
    }
}

/// Width of `s` in pixels.
pub fn width(s: &str, scale: usize) -> usize {
    s.chars().count() * 6 * scale
}

