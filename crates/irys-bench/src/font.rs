/// Draw `text` into an 8-bit RGB image at `(x, y)`, each font pixel a
/// `scale × scale` block, white on a dark box.
pub fn label(rgb: &mut [u8], w: usize, h: usize, x: usize, y: usize, scale: usize, text: &str) {
    let n = text.chars().count();
    let (bw, bh) = ((6 * n + 2) * scale, 9 * scale);
    for yy in y..(y + bh).min(h) {
        for xx in x..(x + bw).min(w) {
            for c in 0..3 {
                rgb[(yy * w + xx) * 3 + c] /= 4;
            }
        }
    }
    for (i, ch) in text.chars().enumerate() {
        let g = glyph(ch);
        for (r, bits) in g.iter().enumerate() {
            for col in 0..5 {
                if bits >> (4 - col) & 1 == 0 {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        let px = x + (1 + 6 * i + col) * scale + dx;
                        let py = y + (1 + r) * scale + dy;
                        if px < w && py < h {
                            rgb[(py * w + px) * 3..][..3].copy_from_slice(&[255, 255, 255]);
                        }
                    }
                }
            }
        }
    }
}
